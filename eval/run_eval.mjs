const EVAL_DIR = dirname(fileURLToPath(import.meta.url));
const BASE = (process.env.PH_EVAL_BASE || 'https://aisdr-proxy.hdxrope.workers.dev').replace(/\/+$/, '');
const TOKEN = readFileSync(process.env.PH_ADMIN_TOKEN_FILE || resolve(EVAL_DIR, '../../aisdr-proxy/.admin_token'), 'utf8').trim();
const ORIGIN = 'http://localhost';
const SITE_LINK = /^https:\/\/(www\.)?parkhomes-okinawa\.com(\/|$)/;
// 公式サイト・価格表・サイト固有のページから答えられるはずの質問。ここで「答えられない」はおかしい
const ANSWERABLE_TAGS = new Set(['公式FAQ', '価格', 'サイト固有']);

async function post(path, body) {
  const res = await fetch(BASE + path, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', Origin: ORIGIN, Authorization: `Bearer ${TOKEN}` },
    body: JSON.stringify(body),
  });
  const data = await res.json().catch(() => ({}));
  if (!res.ok) {
    const e = new Error(`${path} ${res.status}: ${data?.error?.message || ''}`);
    e.status = res.status; // 5xx/429 は withBackoff が再試行する
    throw e;
  }
  return data;
}

/** Return the list of input cases. Each must have a stable `id`. */
async function loadCases() {
  const all = JSON.parse(readFileSync(join(EVAL_DIR, 'cases.json'), 'utf8'));
  const only = (process.env.EVAL_ONLY || '').split(',').map(s => s.trim()).filter(Boolean);
  const cases = only.length ? all.filter(c => only.includes(c.id)) : all;
  // 並列の最初の数件がそれぞれキャッシュを書くと、その分だけ高くつく。先に1回ずつ温めておく
  if (process.env.EVAL_WARMUP !== '0') {
    await post('/parkhomes/chat', { messages: [{ role: 'user', content: 'こんにちは' }] });
    await post('/parkhomes/admin/judge', { instructions: JUDGE_INSTRUCTIONS, prompt: '（準備のための呼び出し。全項目 true、理由は「準備」で返してください）', schema: JUDGE_SCHEMA });
  }
  return cases.map(c => ({ ...c, prompt: c.messages.join('\n---\n') }));
}

/** 複数ターンは1問ずつ送り、前の答えを履歴に積む（画面と同じ） */
async function runCase(input, ctx) {
  // 採点の点検用: EVAL_FAKE=null（何も答えない）/ oracle（模範をそのまま答える）でアプリを呼ばずに採点だけ流す
  const fake = process.env.EVAL_FAKE;
  if (fake === 'null' || fake === 'oracle') {
    const output = fake === 'null' ? '申し訳ありませんが、お答えできません。' : input.reference;
    const transcript = input.messages.flatMap((q, i, a) => [{ role: 'user', content: q },
      { role: 'assistant', content: i === a.length - 1 ? output : '（省略）' }]);
    return { output, no_kb: fake === 'null', transcript, model: `fake-${fake}`, usage: {}, stop_reason: 'end_turn' };
  }
  const history = [], transcript = [];
  const usage = { input_tokens: 0, output_tokens: 0, cache_read_input_tokens: 0, cache_creation_input_tokens: 0 };
  let last;
  for (const q of input.messages) {
    history.push({ role: 'user', content: q });
    transcript.push({ role: 'user', content: q });
    last = await post('/parkhomes/chat', { messages: history.slice(-10) });
    history.push({ role: 'assistant', content: last.answer });
    transcript.push({ role: 'assistant', content: last.answer }); // no_kb は perf 欄に出す（ここに足すと採点AIが「内部情報の露出」と見る）
    for (const k of Object.keys(usage)) usage[k] += last.usage?.[k] || 0;
  }
  return { output: last.answer, no_kb: !!last.no_kb, transcript, model: last.model, usage, stop_reason: last.stop_reason };
}

// 機械チェック（AIを使わない）
function autoChecks(input, run) {
  const out = run.output, ck = input.checks || {}, fails = [];
  for (const group of ck.must_any || [])
    if (!group.some(w => out.includes(w))) fails.push(`必須語なし: ${group.join(' / ')}`);
  for (const w of ck.must_not || [])
    if (out.includes(w)) fails.push(`禁止語あり: ${w}`);
  const links = [...out.matchAll(/\]\((https?:[^)\s]+)\)/g)].map(m => m[1]);
  const bad = links.filter(u => !SITE_LINK.test(u));
  if (bad.length) fails.push(`公式サイト以外のリンク: ${bad.join(' ')}`);
  if (/\[\[NO_KB\]\]/.test(out)) fails.push('NO_KB の印が答えに残っている');
  if (ck.expect_no_kb && !run.no_kb) fails.push('答えられない質問なのに no_kb が立っていない');
  if (!ck.expect_no_kb && run.no_kb && (input.tags || []).some(t => ANSWERABLE_TAGS.has(t)))
    fails.push('答えられるはずの質問で no_kb が立った');
  return fails;
}

